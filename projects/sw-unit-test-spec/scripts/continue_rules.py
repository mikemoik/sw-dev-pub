#!/usr/bin/env python3
"""Generate the Continue (VS Code / JetBrains) rules from the llm/ guides.

    python3 scripts/continue_rules.py           # write .continue/rules/
    python3 scripts/continue_rules.py --check   # exit 1 if they are out of date

Writes .continue/rules/suts-00-common.md (applies to every units/*/*.tex) and
one suts-<file>.md per content file (applies to units/*/<file>.tex): the guide,
the list of related files to read, the command reference (units/empty/) and
the worked example (units/sample/). Continue adds a rule to the chat when a
file matching its glob is in the chat context. llm/ is the source: edit the
guides there and rerun this script. Standard library only.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from llm_prompt import LLM, RELATED, ROOT, UNITS, fenced

RULES = ROOT / ".continue" / "rules"
GLOB = "**/units/*/{}.tex"
HEADER = (
    "<!-- Generated by scripts/continue_rules.py from llm/ -- "
    "edit llm/ and rerun, don't edit this file. -->\n"
)


def frontmatter(name: str, description: str, glob: str) -> str:
    return f'---\nname: "{name}"\ndescription: "{description}"\nglobs: "{glob}"\n---\n'


def common_rule() -> str:
    body = (LLM / "_common.md").read_text(encoding="utf-8").rstrip()
    return (
        frontmatter(
            "SUTS: common rules",
            "Role, chat protocol and LaTeX rules for the SW unit test spec content files",
            GLOB.format("*"),
        )
        + HEADER
        + "\n"
        + body
        + "\n\n# Where things are\n\n"
        "The engineer works on one content file `units/<unit>/<file>.tex` (the file in "
        "the chat context). The other content files of the same unit are in the same "
        "folder. A file-specific rule names the files you need to read.\n"
    )


def file_rule(file: str) -> str:
    guide = (LLM / f"{file}.md").read_text(encoding="utf-8").rstrip()
    related = RELATED[file]
    if related:
        names = " and ".join(f"`{name}.tex`" for name in related)
        context = (
            f"Before your first answer, read {names} from the same unit folder as the "
            f"`{file}.tex` you work on, for reference (don't edit them unless asked). If "
            "you can't read files, ask the engineer to add them to the chat with `@`.\n"
        )
    else:
        context = "No other files are needed.\n"
    parts = [
        frontmatter(
            f"SUTS: {file}.tex",
            f"How to write and review units/<unit>/{file}.tex of the SW unit test spec",
            GLOB.format(file),
        )
        + HEADER,
        guide + "\n",
        "## Related files\n\n" + context,
        fenced(
            f"Command reference (units/empty/{file}.tex)",
            (UNITS / "empty" / f"{file}.tex").read_text(encoding="utf-8"),
        ),
    ]
    sample = UNITS / "sample" / f"{file}.tex"
    if sample.is_file():
        parts.append(
            fenced(
                f"Worked example from another unit (units/sample/{file}.tex)",
                sample.read_text(encoding="utf-8"),
            )
        )
    return "\n".join(parts)


def expected() -> dict:
    rules = {"suts-00-common.md": common_rule()}
    for file in sorted(RELATED):
        rules[f"suts-{file}.md"] = file_rule(file)
    return rules


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate .continue/rules/ from the llm/ guides."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="don't write; exit 1 if a rule file is missing, stale or extra",
    )
    args = parser.parse_args(argv)

    rules = expected()
    present = {p.name for p in RULES.glob("suts-*.md")} if RULES.is_dir() else set()
    if args.check:
        stale = [
            name
            for name, text in rules.items()
            if not (RULES / name).is_file()
            or (RULES / name).read_text(encoding="utf-8") != text
        ]
        extra = sorted(present - set(rules))
        for name in stale + extra:
            print(f"out of date: .continue/rules/{name}", file=sys.stderr)
        if stale or extra:
            print("run: python3 scripts/continue_rules.py", file=sys.stderr)
            return 1
        print(f"{len(rules)} rule files up to date")
        return 0

    RULES.mkdir(parents=True, exist_ok=True)
    for name in sorted(present - set(rules)):
        (RULES / name).unlink()
    for name, text in rules.items():
        (RULES / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(rules)} rule files to {RULES.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
