#!/usr/bin/env python3
"""Generate the Continue (VS Code / JetBrains) rules from the llm/ guides.

    python3 scripts/continue_rules.py                # write .continue/rules/
    python3 scripts/continue_rules.py --check        # exit 1 if they are out of date
    python3 scripts/continue_rules.py --into DIR     # write into DIR (see vendor.py)

Writes sf-00-common.md (applies to figure files: figures/*.tex, *.mmd) and one
sf-<type>.md per figure type (applies to figures/<type>_*.tex and <type>_*.mmd,
so name figure files after their type, e.g. figures/sequence_ctrl_cycle.tex; in
this project also figures/<document>/<type>[_*].tex):
the guide plus the worked examples from figures/sample/ and mermaid/. Continue adds a
rule to the chat when a file matching its globs is in the chat context. llm/
is the source: edit the guides there and rerun this script. Standard library only.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from llm_prompt import LLM, ROOT, TYPES, examples

RULES = ROOT / ".continue" / "rules"
HEADER = (
    "<!-- Generated by spec-figures scripts/continue_rules.py from llm/ -- "
    "edit llm/ there and rerun, don't edit this file. -->\n"
)


def frontmatter(name: str, description: str, globs: list) -> str:
    items = ", ".join(f'"{g}"' for g in globs)
    return f'---\nname: "{name}"\ndescription: "{description}"\nglobs: [{items}]\n---\n'


def common_rule() -> str:
    body = (LLM / "_common.md").read_text(encoding="utf-8").rstrip()
    return (
        frontmatter(
            "Figures: common rules",
            "Role, chat protocol, TikZ (specfig) and Mermaid rules for figures",
            ["**/figures/*.tex", "**/figures/*/*.tex", "**/*.mmd"],
        )
        + HEADER
        + "\n"
        + body
        + "\n\n# Where things are\n\n"
        "The engineer works on one figure file (the file in the chat context): "
        "`figures/<type>_<name>.tex` for TikZ, `<type>_<name>.mmd` for Mermaid. A rule for the "
        "figure type gives its commands and examples. You only see files the engineer has "
        "added to the chat; you have no tools and don't try to open files yourself.\n"
    )


def type_rule(kind: str) -> str:
    guide = (LLM / f"{kind}.md").read_text(encoding="utf-8").rstrip()
    globs = [
        f"**/figures/{kind}_*.tex",
        f"**/figures/*/{kind}_*.tex",
        f"**/figures/*/{kind}.tex",
        f"**/{kind}_*.mmd",
        f"**/mermaid/{kind}.mmd",
    ]
    parts = [
        frontmatter(
            f"Figures: {kind}",
            f"How to draw a {kind} figure (TikZ specfig or Mermaid)",
            globs,
        )
        + HEADER,
        guide + "\n",
        "## Examples\n",
    ]
    return "\n".join(parts + examples(kind))


def document_rule() -> str:
    body = (LLM / "_document.md").read_text(encoding="utf-8").rstrip()
    return (
        frontmatter(
            "Figures: figure document",
            "document.tex of a spec-figures figure document: commands and rules",
            ["**/figures/*/document.tex"],
        )
        + HEADER
        + "\n"
        + body
        + "\n"
    )


# content files of the document templates (units/, components/, manuals/)
MENU_GLOBS = ["**/units/*/*.tex", "**/components/*/*.tex", "**/manuals/*/*.tex"]


def summary(kind: str) -> tuple:
    """(environment, first sentence of the description) of a guide."""
    text = (LLM / f"{kind}.md").read_text(encoding="utf-8")
    env = re.search(r"\\begin\{(sf[A-Za-z]+)\}", text)
    para = text.split("\n\n", 2)[1].strip()
    first = re.split(r"(?<=[.:])\s", para, maxsplit=1)[0].rstrip(":.")
    return (env.group(1) if env else "?"), first


def menu_rule() -> str:
    """For the templates' content files: the figure types and how to ask for one."""
    lines = [
        "# Figures (specfig)",
        "",
        (
            "This template draws figures with the *specfig* package: a figure is one file "
            "`figures/<type>_<name>.tex` in the folder of the unit, component or manual, "
            "holding one environment with plain data commands; specfig does the layout and "
            "the checks. Types (`type`, environment: what it shows):"
        ),
        "",
    ]
    for kind in TYPES:
        env, first = summary(kind)
        lines.append(f"- `{kind}`, `{env}`: {first}.")
    lines += [
        "",
        "When the engineer asks for a figure:",
        "",
        "1. Pick the type from this list; ask if two fit.",
        (
            "2. Check that the guide of that type (a section *Figure: ...* with its commands) "
            "is in this chat. **If it is not, don't write the figure** and don't invent "
            "commands: name the type and ask the engineer to add the guide, e.g. "
            '"Run `python3 scripts/new_figure.py <folder> sequence ctrl_cycle` and add the '
            'new file to the chat" (Continue then adds the guide) or "Rerun '
            '`scripts/llm_prompt.py` with `--figure sequence`".'
        ),
        (
            "3. With the guide: give the figure file (only the environment) and, as a second "
            "code block, the lines that include it in a free-text block of the content file: "
            "`\\begin{figure}[htbp]`, `\\centering`, `\\InputFigure{<type>_<name>}`, "
            "`\\caption{...}`, `\\label{fig:...}`, `\\end{figure}` (a `raci` matrix is a "
            "table: `\\begin{center}` instead of `figure`)."
        ),
        "",
        "Never write raw TikZ (`tikzpicture`, `\\draw`) for these figure types.",
    ]
    return (
        frontmatter(
            "Figures: menu",
            "The specfig figure types and how to ask for one (content files)",
            MENU_GLOBS,
        )
        + HEADER
        + "\n"
        + "\n".join(lines)
        + "\n"
    )


def expected(document: bool = True, menu: bool = False) -> dict:
    """The rules: document = the figure-document rule (this project), menu = the
    figure menu for content files (the templates)."""
    rules = {"sf-00-common.md": common_rule()}
    if document:
        rules["sf-00-document.md"] = document_rule()
    if menu:
        rules["sf-00-menu.md"] = menu_rule()
    for kind in TYPES:
        rules[f"sf-{kind}.md"] = type_rule(kind)
    return rules


def sync(
    rules_dir: Path, check: bool, document: bool = True, menu: bool = False
) -> int:
    rules = expected(document, menu)
    present = (
        {p.name for p in rules_dir.glob("sf-*.md")} if rules_dir.is_dir() else set()
    )
    if check:
        stale = [
            name
            for name, text in rules.items()
            if not (rules_dir / name).is_file()
            or (rules_dir / name).read_text(encoding="utf-8") != text
        ]
        extra = sorted(present - set(rules))
        for name in stale + extra:
            print(f"out of date: {rules_dir / name}", file=sys.stderr)
        if stale or extra:
            return 1
        print(f"{len(rules)} rule files up to date in {rules_dir}")
        return 0
    rules_dir.mkdir(parents=True, exist_ok=True)
    for name in sorted(present - set(rules)):
        (rules_dir / name).unlink()
    for name, text in rules.items():
        (rules_dir / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(rules)} rule files to {rules_dir}")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the figure rules for Continue."
    )
    parser.add_argument(
        "--check", action="store_true", help="don't write; exit 1 if out of date"
    )
    parser.add_argument(
        "--into", type=Path, help="rules folder to write (default .continue/rules)"
    )
    args = parser.parse_args(argv)
    rc = sync(args.into or RULES, args.check)
    if rc:
        print("run: python3 scripts/continue_rules.py", file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())
