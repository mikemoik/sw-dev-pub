#!/usr/bin/env python3
"""Convert a GitLab issue CSV export into manuals/<manual>/opl.tex.

    python3 scripts/gitlab_opl.py <manual> <export.csv> [--date YYYY-MM-DD]
                                  [--source TEXT] [--comment COLUMN] [--force]
    python3 scripts/gitlab_opl.py <manual> <export.csv> --slim OUT.csv

Mapping (GitLab: Issues list -> Export as CSV):
  ID           Issue ID, as \\#<iid>
  topic        Title
  status       State closed -> closed; label workflow::in progress -> in progress;
               else open
  top rank     label top::1 ... top::5
  responsible  Assignee
  date         Due Date; for closed issues the date of Closed At
  comment      empty, or the column named with --comment (e.g. Milestone)

The as-of date (--date, default today) is the date of the export; due dates
before it are marked overdue. An opl.tex with open points is overwritten only
if this script wrote it (or with --force). The template marks inconsistencies in red (e.g. a closed
issue that still has a top:: label).

--slim writes only the columns above (no Description) to OUT.csv, as small
input for the chat LLM when an export does not follow these conventions
(llm/opl.md). Standard library only.
"""

import argparse
import csv
import datetime
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANUALS = ROOT / "manuals"
NAME_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]*")
DATE_RE = re.compile(r"\s*(\d{4}-\d{2}-\d{2})")
MARKER = "% Generated by scripts/gitlab_opl.py"
IN_PROGRESS = "workflow::in progress"
TOP_RE = re.compile(r"top::\s*(\S+)", re.IGNORECASE)

# field -> accepted header names (lowercase, without "(utc)")
COLUMNS = {
    "id": ["issue id", "iid"],
    "title": ["title"],
    "state": ["state"],
    "assignee": ["assignee"],
    "due": ["due date"],
    "closed": ["closed at"],
    "labels": ["labels"],
    "milestone": ["milestone"],
}
REQUIRED = ["id", "title", "state"]

LATEX_SPECIAL = {
    "\\": r"\textbackslash{}",
    "{": r"\{",
    "}": r"\}",
    "&": r"\&",
    "%": r"\%",
    "#": r"\#",
    "$": r"\$",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}

HEADER = """\
{marker} from {export} on {today}.
% Rerun the script instead of editing; see llm/opl.md for exports that don't
% follow the conventions (workflow::in progress, top::1 ... top::5).

% {{as-of date YYYY-MM-DD}}{{source of the export}}
\\OpenPointExport{{{date}}}{{{source}}}

% [top rank 1-5]{{ID}}{{topic}}{{status: open | in progress | closed}}{{responsible}}
%   {{date: due (open, in progress) or closed on (closed)}}{{comment / result}}
"""


def norm(header: str) -> str:
    return re.sub(r"\(utc\)", "", header.lower()).strip()


def tex(text: str) -> str:
    text = " ".join(text.split())  # line breaks and runs of spaces -> one space
    return "".join(LATEX_SPECIAL.get(c, c) for c in text)


def date_of(text: str) -> str:
    match = DATE_RE.match(text or "")
    return match.group(1) if match else (text or "").strip()


def read_export(path: Path):
    csv.field_size_limit(sys.maxsize)
    with path.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        headers = {norm(h): h for h in reader.fieldnames or []}
        cols = {}
        for field, names in COLUMNS.items():
            cols[field] = next((headers[n] for n in names if n in headers), None)
        missing = [f for f in REQUIRED if cols[f] is None]
        if missing:
            raise ValueError(
                "not a GitLab issue export: no column "
                + ", ".join(COLUMNS[f][0].title() for f in missing)
            )
        return cols, headers, list(reader)


def labels_of(row: dict, cols: dict) -> list:
    raw = row.get(cols["labels"], "") if cols["labels"] else ""
    return [label.strip() for label in raw.split(",") if label.strip()]


def open_point(row: dict, cols: dict, comment_col) -> tuple:
    get = lambda field: (row.get(cols[field]) or "").strip() if cols[field] else ""
    labels = labels_of(row, cols)
    lower = [label.lower() for label in labels]
    if get("state").lower() == "closed":
        status, date = "closed", date_of(get("closed")) or date_of(get("due"))
    else:
        status = "in progress" if IN_PROGRESS in lower else "open"
        date = date_of(get("due"))
    ranks = [m.group(1) for m in map(TOP_RE.fullmatch, labels) if m]
    rank = f"[{tex(ranks[0])}]" if ranks else ""
    comment = tex((row.get(comment_col) or "").strip()) if comment_col else ""
    ident = get("id")
    ident = tex(ident if ident.startswith("#") else f"#{ident}")
    return status, (
        f"\\OpenPoint{rank}{{{ident}}}{{{tex(get('title'))}}}{{{status}}}"
        f"{{{tex(get('assignee'))}}}{{{date}}}{{{comment}}}"
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Convert a GitLab issue CSV export into manuals/<manual>/opl.tex."
    )
    parser.add_argument("manual", help="manual folder name under manuals/")
    parser.add_argument("export", type=Path, help="GitLab issue export (CSV)")
    parser.add_argument(
        "--date", help="as-of date of the export, YYYY-MM-DD (default: today)"
    )
    parser.add_argument(
        "--source", help="source line (default: GitLab issue export <file name>)"
    )
    parser.add_argument(
        "--comment",
        metavar="COLUMN",
        help="export column for the comment, e.g. Milestone",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an opl.tex not written by this script",
    )
    parser.add_argument(
        "--slim",
        type=Path,
        metavar="OUT",
        help="write only the needed columns to OUT.csv (LLM input) instead of opl.tex",
    )
    args = parser.parse_args(argv)

    target = MANUALS / args.manual / "opl.tex"
    if (
        not NAME_RE.fullmatch(args.manual)
        or not (MANUALS / args.manual / "metadata.tex").is_file()
    ):
        print(f"error: no manual {args.manual!r} under {MANUALS}", file=sys.stderr)
        return 2
    if not args.export.is_file():
        print(f"error: export not found: {args.export}", file=sys.stderr)
        return 2
    today = datetime.date.today().isoformat()
    date = args.date or today
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
        print(f"error: --date {date!r} is not YYYY-MM-DD", file=sys.stderr)
        return 2
    try:
        cols, headers, rows = read_export(args.export)
    except (ValueError, csv.Error, UnicodeDecodeError) as err:
        print(f"error: {args.export}: {err}", file=sys.stderr)
        return 2
    comment_col = None
    if args.comment:
        comment_col = headers.get(norm(args.comment))
        if comment_col is None:
            print(f"error: no column {args.comment!r} in the export", file=sys.stderr)
            return 2

    if args.slim:
        keep = [c for c in cols.values() if c] + ([comment_col] if comment_col else [])
        keep = list(dict.fromkeys(keep))
        with args.slim.open("w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(keep)
            for row in rows:
                writer.writerow([" ".join((row.get(c) or "").split()) for c in keep])
        print(f"wrote {len(rows)} issues, {len(keep)} columns to {args.slim}")
        return 0

    if target.is_file() and not args.force:
        old = target.read_text(encoding="utf-8")
        written = old.lstrip().startswith(MARKER)
        has_points = any(
            line.lstrip().startswith("\\OpenPoint") for line in old.splitlines()
        )
        if has_points and not written:
            print(
                f"error: {target.relative_to(ROOT)} has open points not written by this "
                "script; use --force to overwrite it",
                file=sys.stderr,
            )
            return 2
    source = args.source or f"GitLab issue export {args.export.name}"
    lines = [
        HEADER.format(
            marker=MARKER,
            export=tex(args.export.name),
            today=today,
            date=date,
            source=tex(source),
        )
    ]
    counts = {}
    for row in rows:
        status, line = open_point(row, cols, comment_col)
        lines.append(line)
        counts[status] = counts.get(status, 0) + 1
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    summary = ", ".join(f"{n} {s}" for s, n in sorted(counts.items()))
    print(f"wrote {target.relative_to(ROOT)}: {len(rows)} issues ({summary or 'none'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
